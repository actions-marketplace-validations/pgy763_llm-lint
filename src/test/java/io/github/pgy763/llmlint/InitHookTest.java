package io.github.pgy763.llmlint;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

import java.io.IOException;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

class InitHookTest {

    private record Result(int code, String out, String err) {
    }

    private static Result run(String... args) {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        CommandLine command = new CommandLine(new Main());
        command.setOut(new PrintWriter(out, true));
        command.setErr(new PrintWriter(err, true));
        int code = command.execute(args);
        return new Result(code, out.toString(), err.toString());
    }

    private static Path gitRepo(Path dir) throws IOException {
        Files.createDirectories(dir.resolve(".git/hooks"));
        return dir;
    }

    @Test
    void 在git仓库里写出hook(@TempDir Path tmp) throws IOException {
        Path repo = gitRepo(tmp);
        Result result = run("--init-hook", repo.toString());

        assertEquals(0, result.code(), result.err());
        Path hook = repo.resolve(".git/hooks/pre-commit");
        assertTrue(Files.isRegularFile(hook), "pre-commit 应该被写出来");
        String text = Files.readString(hook, StandardCharsets.UTF_8);
        assertTrue(text.startsWith("#!/bin/sh"), text);
        assertTrue(text.contains("git diff --cached --name-only --diff-filter=ACMR -- '*.java'"), text);
        assertTrue(text.contains("--fail-on error"), text);
        assertTrue(result.out().contains("pre-commit"), result.out());

        if (Files.getFileStore(hook).supportsFileAttributeView("posix")) {
            assertTrue(Files.isExecutable(hook), "posix 上要 chmod +x");
        }
    }

    @Test
    void 已经有hook时不覆盖(@TempDir Path tmp) throws IOException {
        Path repo = gitRepo(tmp);
        Path hook = repo.resolve(".git/hooks/pre-commit");
        Files.writeString(hook, "#!/bin/sh\necho mine\n", StandardCharsets.UTF_8);

        Result result = run("--init-hook", repo.toString());

        assertEquals(2, result.code(), result.err());
        assertTrue(result.err().contains("不覆盖"), result.err());
        assertTrue(Files.readString(hook, StandardCharsets.UTF_8).contains("echo mine"));
    }

    @Test
    void 不是git仓库时退出2(@TempDir Path tmp) {
        Result result = run("--init-hook", tmp.toString());

        assertEquals(2, result.code(), result.err());
        assertTrue(result.err().contains(".git"), result.err());
        assertFalse(Files.exists(tmp.resolve(".git")));
    }

    @Test
    void 英文模式写英文注释(@TempDir Path tmp) throws IOException {
        Path repo = gitRepo(tmp);
        Result result = run("--lang", "en", "--init-hook", repo.toString());

        assertEquals(0, result.code(), result.err());
        String text = Files.readString(repo.resolve(".git/hooks/pre-commit"), StandardCharsets.UTF_8);
        assertTrue(text.contains("generated by `llm-lint --init-hook`"), text);
        assertTrue(text.contains("not found, skipping"), text);
        assertFalse(text.contains("跳过检查"), text);
    }

    @Test
    void 帮助里有init_hook() {
        Result result = run("--help");
        assertEquals(0, result.code());
        assertTrue(result.out().contains("--init-hook"), result.out());
    }
}