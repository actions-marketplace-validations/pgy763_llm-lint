package io.github.pgy763.llmlint.report;

import io.github.pgy763.llmlint.Finding;
import io.github.pgy763.llmlint.lang.Messages;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * 一份可以双击打开的 HTML 报告：不依赖网络、不用 JS，发给没装工具的人也能看。
 *
 * <p>样式全部内联在 &lt;style&gt; 里，文件拷到哪里都能打开。内容按文件分组，一行一个问题，
 * 规则名链到手册页。
 */
public final class HtmlReport {

    private HtmlReport() {
    }

    public static String format(List<Finding> findings, int filesScanned) {
        Map<String, List<Finding>> byFile = new LinkedHashMap<>();
        for (Finding finding : findings) {
            byFile.computeIfAbsent(finding.file(), key -> new ArrayList<>()).add(finding);
        }
        int errors = 0;
        for (Finding finding : findings) {
            if (finding.severity().label().equals("error")) {
                errors++;
            }
        }
        int warnings = findings.size() - errors;

        StringBuilder sb = new StringBuilder();
        sb.append("<!DOCTYPE html>\n<html lang=\"").append(Messages.lang().code()).append("\">\n<head>\n");
        sb.append("<meta charset=\"utf-8\">\n");
        sb.append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        sb.append("<title>llm-lint</title>\n");
        sb.append("<style>\n");
        sb.append(style());
        sb.append("</style>\n</head>\n<body>\n");
        sb.append("<h1>llm-lint</h1>\n");
        if (findings.isEmpty()) {
            sb.append("<p class=\"clean\">")
                    .append(escape(Messages.f("没有发现问题，扫了 %d 个文件。", "No findings. Scanned %d files.",
                            filesScanned)))
                    .append("</p>\n");
        } else {
            sb.append("<p class=\"summary\">")
                    .append(escape(Messages.f("%d 个问题（%d error / %d warning），扫了 %d 个文件。",
                            "%d findings (%d error / %d warning), scanned %d files.",
                            findings.size(), errors, warnings, filesScanned)))
                    .append("</p>\n");
            for (Map.Entry<String, List<Finding>> entry : byFile.entrySet()) {
                sb.append("<h2>").append(escape(entry.getKey())).append("</h2>\n");
                sb.append("<table>\n<thead><tr>")
                        .append("<th>").append(escape(Messages.t("行", "Line"))).append("</th>")
                        .append("<th>").append(escape(Messages.t("级别", "Level"))).append("</th>")
                        .append("<th>").append(escape(Messages.t("规则", "Rule"))).append("</th>")
                        .append("<th>").append(escape(Messages.t("问题", "Problem"))).append("</th>")
                        .append("</tr></thead>\n<tbody>\n");
                for (Finding finding : entry.getValue()) {
                    String level = finding.severity().label();
                    sb.append("<tr class=\"").append(escape(level)).append("\">")
                            .append("<td class=\"line\">").append(finding.line()).append(':')
                            .append(finding.column()).append("</td>")
                            .append("<td><span class=\"tag ").append(escape(level)).append("\">")
                            .append(escape(level)).append("</span></td>")
                            .append("<td><a href=\"").append(escape(finding.docUrl())).append("\">")
                            .append(escape(finding.ruleId())).append("</a></td>")
                            .append("<td>").append(escape(finding.message())).append("</td>")
                            .append("</tr>\n");
                }
                sb.append("</tbody>\n</table>\n");
            }
        }
        sb.append("<footer>")
                .append(escape(Messages.t("由 llm-lint 生成 · 规则说明见 docs/rules.md",
                        "Generated by llm-lint · rule reference: docs/rules.md")))
                .append("</footer>\n</body>\n</html>\n");
        return sb.toString();
    }

    private static String style() {
        return """
                :root { color-scheme: light dark; }
                body { font: 15px/1.5 -apple-system, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
                       margin: 0 auto; max-width: 1100px; padding: 24px; }
                h1 { font-size: 22px; margin: 0 0 4px; }
                h2 { font-size: 15px; font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;
                     margin: 28px 0 6px; word-break: break-all; }
                .summary { margin: 0 0 8px; font-weight: 600; }
                .clean { margin: 0 0 8px; color: #1a7f37; font-weight: 600; }
                table { border-collapse: collapse; width: 100%; }
                th, td { text-align: left; padding: 6px 8px; border-bottom: 1px solid #8883;
                         vertical-align: top; }
                th { font-size: 12px; text-transform: uppercase; letter-spacing: .04em; color: #888; }
                td.line { font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;
                          white-space: nowrap; color: #888; }
                .tag { display: inline-block; padding: 1px 6px; border-radius: 999px; font-size: 12px; }
                .tag.error { background: #ffebe9; color: #b3261e; }
                .tag.warning { background: #fff4ce; color: #7a5d00; }
                .tag.info { background: #e7f0ff; color: #1f4fa8; }
                footer { margin-top: 32px; color: #888; font-size: 12px; }
                @media (prefers-color-scheme: dark) {
                    .tag.error { background: #4a1d1b; color: #ffb4ab; }
                    .tag.warning { background: #463a00; color: #ffdf88; }
                    .tag.info { background: #1b2f4d; color: #a9c7ff; }
                    .clean { color: #6fdd8b; }
                }
                """;
    }

    static String escape(String value) {
        StringBuilder sb = new StringBuilder(value.length() + 16);
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '&' -> sb.append("&amp;");
                case '<' -> sb.append("&lt;");
                case '>' -> sb.append("&gt;");
                case '"' -> sb.append("&quot;");
                case '\'' -> sb.append("&#39;");
                default -> sb.append(c);
            }
        }
        return sb.toString();
    }
}